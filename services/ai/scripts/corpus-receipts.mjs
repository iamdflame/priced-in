// What the corpus fetched for each receipt of corpus/ERRORS.json: its URL, the HTTP status, the
// sha256 of the bytes and when, from corpus/receipts/evidence-index.json (and a committed receipt
// file's own sha256). The receipt check (services/ai/src/receipts.js) reads the result to report
// our Checker's receipts without fetching them again, including on Vercel, where corpus/receipts/
// is not uploaded. services/ai/test/receipts.test.mjs fails if the committed copy drifts.
//
//   node services/ai/scripts/corpus-receipts.mjs           write services/ai/src/corpus-receipts.json
//   node services/ai/scripts/corpus-receipts.mjs --check   exit 1 if the committed copy differs
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const OUT = path.join(ROOT, "services/ai/src/corpus-receipts.json");

/** The committed metadata, rebuilt from the corpus's own files. */
export function buildCorpusReceipts(root = ROOT) {
  const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));
  const errors = read("corpus/ERRORS.json").items;
  const extracts = read("corpus/receipts/extracts.json");
  const index = read("corpus/receipts/evidence-index.json");
  const items = {};
  for (const e of errors) {
    items[e.id] = (e.receipts || []).map((r) => {
      const x = (extracts[e.id]?.receipts || []).find((q) => q.url === r.url && q.match === r.match);
      if (!x) throw new Error(`${e.id}: no extract for receipt ${r.url}`);
      if (x.key.startsWith("file:")) {
        const file = `corpus/${x.key.slice(5)}`;
        const buf = fs.readFileSync(path.join(root, file));
        return { url: r.url, key: x.key, file, status: null, sha256: createHash("sha256").update(buf).digest("hex"), bytes: buf.length, fetched_at: null, post: false };
      }
      const i = index[x.key];
      if (!i) throw new Error(`${e.id}: no index entry ${x.key}`);
      return { url: r.url, key: x.key, file: null, status: i.status, sha256: i.sha256, bytes: i.bytes, fetched_at: i.fetchedAt, post: Boolean(i.post) };
    });
  }
  return {
    note: "What the corpus fetched for each receipt in corpus/ERRORS.json: the HTTP status, the sha256 of the bytes and when (corpus/receipts/evidence-index.json), or a committed receipt file's own sha256. post: the corpus asked with a JSON-RPC POST, which a plain GET of the URL does not repeat. Generated by services/ai/scripts/corpus-receipts.mjs.",
    items,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(buildCorpusReceipts(), null, 1) + "\n";
  if (process.argv.includes("--check")) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === text;
    console.log(same ? "services/ai/src/corpus-receipts.json matches the corpus" : "services/ai/src/corpus-receipts.json differs from the corpus: run node services/ai/scripts/corpus-receipts.mjs");
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
