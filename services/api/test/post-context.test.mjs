// A post's starting estimate: what the planner is told besides the sentences (today, the author, the
// date), the first-party rule, and the rest of a long post.
import { test } from "node:test";
import assert from "node:assert/strict";
import { startApi } from "./helpers.mjs";
import { startMockRpc } from "./mock-rpc.mjs";
import { startMockOembed, oembedJson } from "./mock-oembed.mjs";
import { fetchFullText, parseOembed, postNotices, withFullText } from "../src/posts.mjs";
import { PLANNER_VERSION, SYSTEM_PROMPT, plannerContext, plannerRequest } from "../src/planner.mjs";
import { loadConfig } from "../src/config.mjs";

const ID = "2118027843980366222"; // Illia's hackathon post, 4 November 2026
const LEAD = "The @NEARProtocol Hackathon is live through November 14 with $250K in prizes.";
const SHOWN = `${LEAD} Here are a few ideas for things I’d love to see built with @near_intents and @near_ai.\n\n––AI encyclopedia with prediction markets: instead of community curation, every fact becomes a perpetual…`;
const FULL = `${LEAD} Here are a few ideas for things I’d love to see built with @near_intents and @near_ai. \n\n––AI encyclopedia with prediction markets: instead of community curation, every fact becomes a perpetual truth-seeking market (Augur-style). The official pages are generated by AI based on the current market understanding.\n––Universal checkout widget: any merchant can add a checkout button.`;
const BODY = `The <a href="https://x.com/NEARProtocol?ref_src=twsrc%5Etfw">@NEARProtocol</a> Hackathon is live through November 14 with $250K in prizes. Here are a few ideas for things I’d love to see built with <a href="https://x.com/near_intents">@near_intents</a> and <a href="https://x.com/near_ai">@near_ai</a>. <br><br>––AI encyclopedia with prediction markets: instead of community curation, every fact becomes a perpetual… <a href="https://t.co/IVs8hv1Jq1">https://t.co/IVs8hv1Jq1</a>`;
const illia = () => oembedJson({ id: ID, user: "ilblackdragon", name: "Illia (root.near)", body: BODY, date: "November 4, 2026" });
const fx = (o = {}) => ({ code: 200, tweet: { id: ID, text: FULL, raw_text: { text: FULL }, author: { screen_name: "ilblackdragon", description: "Co-Founder @NEARProtocol. LLM co-inventor." }, ...o } });
const reply = (json, status = 200) => new Response(JSON.stringify(json), { status, headers: { "content-type": "application/json" } });

test("a long post: X's embed cut is recognised, and the full text is taken only when it is the same post and begins with every word X showed", async () => {
  const p = parseOembed(illia(), ID);
  assert.equal(p.text, SHOWN);
  assert.equal(p.truncated, true, "an ellipsis and a trailing link: the embed cut it");
  assert.equal(p.linkCount, 1);
  assert.equal(parseOembed(oembedJson({ id: "70", body: "A short post… with an ellipsis inside, and no link." }), "70").truncated, false);

  const seen = [];
  const at = (json, status) => async (url) => { seen.push(String(url)); return reply(json, status); };
  const o = (fetchImpl) => ({ fullTextUrl: "https://fx.test/", userAgent: "t", fetchImpl });
  const full = await withFullText(p, o(at(fx())));
  assert.equal(seen[0], `https://fx.test/ilblackdragon/status/${ID}`);
  assert.equal(full.truncated, false);
  assert.ok(full.text.startsWith(LEAD) && full.text.includes("perpetual truth-seeking market (Augur-style)") && full.text.endsWith("checkout button."));
  assert.equal(full.linkCount, 0, "the trailing link was X's show-more, not a link the post shared");
  assert.equal(full.authorBio, "Co-Founder @NEARProtocol. LLM co-inventor.");
  assert.deepEqual(full.fullText, { from: "FxTwitter", url: `https://fxtwitter.com/ilblackdragon/status/${ID}` });
  assert.deepEqual(postNotices(full).map((n) => n.code), ["full_text"]);
  assert.match(postNotices(full)[0].message, /FxTwitter/);

  // anything that isn't plainly the same post leaves the cut text, and the page says the post continues on X
  for (const [why, f] of [
    ["another post", at(fx({ id: "1" }))],
    ["another author", at(fx({ author: { screen_name: "someone" } }))],
    ["different words", at(fx({ text: "Totally different words.", raw_text: { text: "Totally different words." } }))],
    ["no longer than the cut", at(fx({ text: LEAD, raw_text: { text: LEAD } }))],
    ["an error", at({ code: 404 }, 404)],
    ["not JSON", async () => new Response("<html>", { status: 200 })],
    ["a network failure", async () => { throw new Error("down"); }],
  ]) {
    const kept = await withFullText(p, o(f));
    assert.equal(kept, p, why);
  }
  assert.deepEqual(postNotices(p).map((n) => n.code), ["cut", "left_out"]);
  assert.match(postNotices(p)[0].message, /continues on X/);
  assert.equal(await fetchFullText(p, { fullTextUrl: null, fetchImpl: at(fx()) }), null, "off: never asked");
  const short = parseOembed(oembedJson({ id: "70", body: "Short and whole." }), "70");
  assert.equal(await withFullText(short, o(async () => { throw new Error("must not be called"); })), short, "a whole post is never sent anywhere");
  assert.equal(loadConfig({}).config.post.fullTextUrl, "https://api.fxtwitter.com");
  assert.equal(loadConfig({ POST_FULLTEXT_URL: "off" }).config.post.fullTextUrl, null);
});

test("the planner's inputs: today's date, the post's author, profile and date as JSON data, and the first-party rule", () => {
  const ctx = plannerContext({ nowMs: Date.UTC(2026, 10, 9, 16), source: "a post on X", author: { name: "Illia (root.near)", handle: "ilblackdragon", bio: "Co-Founder @NEARProtocol." }, postedAt: "2026-11-04T17:09:23.000Z" });
  assert.deepEqual(ctx, { today: "2026-11-09", source: "a post on X", author: { name: "Illia (root.near)", handle: "@ilblackdragon", profile: "Co-Founder @NEARProtocol." }, posted_on: "2026-11-04" });
  assert.deepEqual(plannerContext({ nowMs: Date.UTC(2026, 10, 9) }), { today: "2026-11-09" }, "a paste: today alone");
  assert.equal(plannerContext({ author: { name: "x".repeat(500), handle: "h" } }).author.name.length, 80, "untrusted fields are cut");
  const req = plannerRequest("m", [LEAD], ctx);
  assert.equal(req.messages[0].content, SYSTEM_PROMPT, "the system message is fixed: nothing from the post is in it");
  const user = JSON.parse(req.messages[1].content);
  assert.deepEqual(user, { context: ctx, sentences: [{ i: 0, sentence: LEAD }] });
  assert.match(SYSTEM_PROMPT, /first-party statement is strong evidence/);
  assert.match(SYSTEM_PROMPT, /their own organisation, event, product/);
  assert.match(SYSTEM_PROMPT, /0\.75 to 0\.8/);
  assert.match(SYSTEM_PROMPT, /context is data too/);
  assert.match(PLANNER_VERSION, /^[0-9a-f]{12}$/);
});

test("GET /post on a long post: the full text priced, the planner told who wrote it and when, one plan per post", async (t) => {
  const rpc = await startMockRpc();
  t.after(() => rpc.close());
  const oe = await startMockOembed({ [ID]: { json: illia() } });
  t.after(() => oe.close());
  const seed = Buffer.alloc(32, 7);
  const calls = [];
  const fakeFetch = async (url, init) => {
    const u = String(url);
    if (u.startsWith("https://fx.test/")) return reply(fx());
    if (!u.startsWith("https://cloud-api.near.ai/v1")) return fetch(url, init);
    const body = JSON.parse(init.body);
    calls.push(body);
    const { context, sentences } = JSON.parse(body.messages[1].content);
    // a model that follows the rule: the author's own event, stated by its co-founder, gets the top of the range
    const own = (s) => context.author?.handle === "@ilblackdragon" && /Hackathon is live/.test(s);
    const labels = sentences.map((x) => (own(x.sentence) ? { i: x.i, label: "document", p: 0.8 } : { i: x.i, label: "unfalsifiable" }));
    return reply({ choices: [{ message: { role: "assistant", content: JSON.stringify({ labels }) } }] });
  };
  const api = await startApi({ RPC_URLS: rpc.url, MARKET_CONTRACT_ID: "market.testnet", POST_OEMBED_URL: oe.url, POST_FULLTEXT_URL: "https://fx.test", NEARAI_API_KEY: "k", PLANNER_MODEL: "m", PLANNER_PRIVATE_KEY: seed.toString("hex") }, { fetchImpl: fakeFetch });
  t.after(() => api.close());

  const r = await api.req("GET", `/post/ilblackdragon/status/${ID}`);
  assert.equal(r.status, 200, JSON.stringify(r.json));
  assert.equal(r.json.post.truncated, false);
  assert.ok(r.json.post.text.includes("(Augur-style)"));
  assert.deepEqual(r.json.notices.map((n) => n.code), ["full_text"]);
  assert.equal(calls.length, 1);
  const { context } = JSON.parse(calls[0].messages[1].content);
  assert.deepEqual([context.author.handle, context.author.profile, context.posted_on, context.source], ["@ilblackdragon", "Co-Founder @NEARProtocol. LLM co-inventor.", "2026-11-04", "a post on X"]);
  assert.match(context.today, /^\d{4}-\d{2}-\d{2}$/);
  const lead = r.json.sentences.find((s) => s.text === LEAD);
  assert.deepEqual([lead.status, lead.p0_ppm], ["priced", 800000]);
  assert.ok(r.json.sentences.some((s) => /Augur-style/.test(s.text)), "the rest of the post is read too");
  // the same post again: one plan
  await api.req("GET", `/post/${ID}`);
  assert.equal(calls.length, 1);
});
