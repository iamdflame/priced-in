// Regenerates test/fixtures/rewrite-signed.json: one real rewrite record produced by
// services/ai's writer against its offline NEAR AI stand-in (services/ai/test/mock-nearai.mjs),
// which signs provider_tee-style over the exact request and response bytes with a local key.
// The web's verify tests check this record, and forgeries of it, without any network.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { NearAI, Attestor, verifyProvenance } from "../../services/ai/src/nearai.js";
import { Writer } from "../../services/ai/src/writer.js";
import { EventHub } from "../../services/api/src/events.mjs";
import { RewriteStore } from "../../services/api/src/rewrites.mjs";
import { startMockNearAI, MOCK_MODELS } from "../../services/ai/test/mock-nearai.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const M = MOCK_MODELS[2];
const claims = [
  { id: 0, page: "near-intents", text: "NEAR Intents has processed more than $10 billion in cumulative volume.", price_yes_ppm: 500000 },
  { id: 1, page: "near-intents", text: "NEAR Intents launched in 2024.", price_yes_ppm: 900000 },
];
const mock = await startMockNearAI();
try {
  const client = new NearAI({ apiKey: mock.apiKey, baseUrl: mock.url });
  const attestor = new Attestor({ client, quoteVerifier: mock.quoteVerifier, gpuVerifier: mock.gpuVerifier });
  const store = new RewriteStore();
  const writer = new Writer({
    client, attestor, model: M, store, hub: new EventHub(), signatureDeadlineMs: 3000,
    claims: { one: async (id) => claims.find((c) => c.id === id) || null, byPage: async (p) => claims.filter((c) => c.page === p) },
  });
  const rec = await writer.onTrade({ uid: "fixture", event: "trade", data: { claim_id: 0, trader: "lane:ed25519:fixture", side: "no", price_yes_ppm: 358265 }, txHash: "fixtureTx" });
  if (rec?.status !== "signed") throw new Error(`expected a signed rewrite, got ${rec?.status}: ${rec?.provenance?.reason}`);
  const check = verifyProvenance(rec.provenance, { signing_address: mock.signerHex(M) });
  if (!check.ok) throw new Error(`services/ai's own check failed: ${check.reasons.join("; ")}`);
  const out = { note: "Generated by web/scripts/make-fixture.mjs from services/ai's writer and its offline NEAR AI stand-in. The key is a throwaway.", model: M, signer: mock.signerHex(M), record: rec };
  const file = path.join(here, "../test/fixtures/rewrite-signed.json");
  fs.writeFileSync(file, JSON.stringify(out, null, 1) + "\n");
  console.log(`wrote ${path.relative(process.cwd(), file)}: ${rec.id} ${rec.status} by ${M} (${mock.signerHex(M).slice(0, 12)}…)`);
} finally {
  await mock.close?.();
  setTimeout(() => process.exit(process.exitCode ?? 0), 50).unref();
}
